def _compact_eclipse_values(values: list) -> list:
    """Encode repeated numeric values with Eclipse run-length syntax.

    Parameters
    ----------
    values : list
        Values to encode in their existing global order.

    Returns
    -------
    list
        Eclipse-formatted strings using ``n*value`` compaction."""
    if len(values) == 0:
        return []
    v = np.asarray(values, dtype=np.float64)
    change = np.concatenate(([True], v[1:] != v[:-1]))
    idx = np.flatnonzero(change)
    counts = np.diff(np.append(idx, v.size))
    uniq = v[idx]
    out = []
    for val, n in zip(uniq, counts):
        if n > 1:
            if val == 0:
                out.append(f"{n}*0 ")
            elif val.is_integer():
                out.append(f"{n}*{int(val)} ")
            else:
                out.append(f"{n}*{val} ")
        else:
            if val == 0:
                out.append("0 ")
            elif val.is_integer():
                out.append(f"{int(val)} ")
            else:
                out.append(f"{val} ")
    return out


def create_corner_point_grid(
    cfg: PofffConfig, xcoord: NDArray, zcoord: NDArray
) -> None:
    """Write OPM COORD and ZCORN data for the corner-point grid.

    Parameters
    ----------
    cfg : PofffConfig
        Shared pofff configuration and derived runtime state.
    xcoord : NDArray
        Corner-point x coordinates arranged by pillar and vertical interface.
    zcoord : NDArray
        Corner-point z coordinates arranged by pillar and vertical interface."""

    nx, nz = cfg.nxz
    nk = nz + 1
    grid = []
    grid.append("COORD\n")
    tmp = []
    for y in [0, cfg.dims[1]]:
        for i in range(nx + 1):
            base = i * nk
            tmp.append(f"{xcoord[base]:E} {y} 0 " f"{xcoord[base + nz]:E} {y:E} 0 ")
    grid.extend(_compact_eclipse_values("".join(tmp).split()))
    grid.append("/\n")
    grid.append("ZCORN\n")
    tmp = []
    for i in range(nx):
        tmp.append(f"{zcoord[i*nk]:E} {zcoord[(i+1)*nk]:E} ")
    tmp.extend(tmp[-nx:])
    for k in range(nz - 1):
        for i in range(nx):
            base = i * nk + k + 1
            tmp.append(f"{zcoord[base]:E} {zcoord[base + nk]:E} ")
        tmp.extend(tmp[-nx:])
        tmp.extend(tmp[-2 * nx :])
    for i in range(nx):
        tmp.append(f"{zcoord[(i+1)*nk - 1]:E} {zcoord[(i+2)*nk - 1]:E} ")
    tmp.extend(tmp[-nx:])
    grid.extend(_compact_eclipse_values("".join(tmp).split()))
    grid.append("/")
    with open(f"{cfg.deck}/GRID.INC", "w", encoding="utf8") as f:
        f.write(HEADER)
        f.write("".join(grid))
        f.write("\n")


def _write_keyword_files(cfg: PofffConfig) -> None:
    """Write generated OPM property and geometry include files.

    Parameters
    ----------
    cfg : PofffConfig
        Shared pofff configuration and derived runtime state."""
    keywords = ["fluxnum", "fipnum"]
    if cfg.grid == "tensor":
        keywords += ["dx", "dz"]
    if cfg.thickness in ("initial", "final"):
        keywords += ["multpv", "multx", "multx-", "multz", "multz-"]
    for name in keywords:
        values = getattr(cfg, "multpv" if name.startswith("mult") else name)
        body = _compact_eclipse_values(values)
        with open(f"{cfg.deck}/{name.upper()}.INC", "w", encoding="utf8") as f:
            f.write(HEADER)
            f.write(f"{name.upper()}\n")
            f.writelines(body)
            f.write("/\n")


def write_files(cfg: PofffConfig) -> None:
    """Generate the OPM deck and optional ERT or Everest files.

    Generated files are written below ``cfg.deck``, ``cfg.jobs``, and ``cfg.fol``
    according to the selected workflow.

    Parameters
    ----------
    cfg : PofffConfig
        Shared pofff configuration and derived runtime state."""
    _write_keyword_files(cfg)
    tmpl = Template(filename=f"{cfg.path}/templates/deck.mako")
    mytemplate = tmpl.render(
        nxz=cfg.nxz,
        grid=cfg.grid,
        deck=cfg.deck,
        dims=cfg.dims,
        diffusion=cfg.diffusion,
        multpv=cfg.multpv,
        hm=cfg.hm,
        pressure=cfg.pressure,
        temperature=cfg.temperature,
        sensor_ik=cfg.sensor_ik,
        source_ik=cfg.source_ik,
        inj=cfg.inj,
        tuning=cfg.tuning,
    )
    with open(f"{cfg.deck}/{cfg.data}.DATA", "w", encoding="utf8") as f:
        f.write(mytemplate)
    job_names = ["bcprop", "equalreg", "satufunc"]
    _render_boundary_properties_script(cfg)
    _render_region_properties_script(cfg)
    _render_saturation_functions_script(cfg)
    if cfg.everert:
        _render_flow_script(cfg)
        _render_copy_script(cfg)
        job_names += ["flow", "copyd"]
        if cfg.popsize:
            job_names += ["scale"]
            _render_scale_script(cfg)
            with open(f"{cfg.jobs}/METRIC", "w", encoding="utf8") as f:
                f.write("EXECUTABLE metric.py")

            with open(f"{cfg.jobs}/DATA", "w", encoding="utf8") as f:
                f.write("EXECUTABLE data.py")
            _render_everest_configuration(cfg)
        else:
            with open(f"{cfg.jobs}/METRIC", "w", encoding="utf8") as f:
                f.write("EXECUTABLE metric.py\n")
                f.write(
                    f"ARGLIST -t {cfg.times} -e {cfg.experiment} "
                    f"-s {cfg.msat} -c {cfg.mcon} -p {cfg.path}"
                )
            with open(f"{cfg.jobs}/DATA", "w", encoding="utf8") as f:
                f.write("EXECUTABLE data.py\n")
                f.write(f"ARGLIST -t {cfg.times} -m {cfg.deck}/cellmap.npy")
            _render_ert_configuration(cfg)
        if cfg.monotonic:
            _render_monotonic_script(cfg)
            job_names += ["monotonic"]
    for name in job_names:
        script_path = f"{cfg.jobs}/{name}.py"
        os.chmod(script_path, 0o755)
        if cfg.mode in ["single", "files"] and not cfg.everert:
            subprocess.run(["python3", script_path], check=True)
            os.remove(script_path)
    if cfg.ertargs and cfg.everert:
        assert cfg.errors
        with open(f"{cfg.deck}/obs.txt", "w", encoding="utf8") as f:
            f.write("\n".join(f"0 {error}" for error in cfg.errors) + "\n")
        with open(f"{cfg.deck}/para.txt", "w", encoding="utf8") as f:
            f.write(
                "\n".join(
                    f"{para} {cfg.hm[para][0].upper()} {cfg.hm[para][1]} {cfg.hm[para][2]}"
                    for para in cfg.hm
                )
                + "\n"
            )
        content = "{\n" + ",\n".join(f'"{para}": <{para}>' for para in cfg.hm) + "\n}\n"
        with open(f"{cfg.deck}/prior.tmpl", "w", encoding="utf8") as f:
            f.write(content)


def _render_monotonic_script(cfg: PofffConfig) -> None:
    """Render the generated monotonicity-check job script.

    Parameters
    ----------
    cfg : PofffConfig
        Shared pofff configuration and derived runtime state."""
    inc_names = ["swi", "sni", "pen", "nkrw", "nkrn", "npe"]
    dec_names = ["perm", "permx", "permz", "disperc"]

    inc_lines = []
    for name in inc_names:
        keys = [f"{name}{i}" for i in range(1, 8) if f"{name}{i}" in cfg.hm]
        for prev, cur in pairwise(keys):
            inc_lines.append(
                f"if coef['{prev}'] < coef['{cur}']:\n" f"    nomonotonic = True"
            )

    dec_lines = []
    for name in dec_names:
        keys = [f"{name}{i}" for i in reversed(range(1, 8)) if f"{name}{i}" in cfg.hm]
        for prev, cur in pairwise(keys):
            dec_lines.append(
                f"if coef['{prev}'] < coef['{cur}']:\n" f"    nomonotonic = True"
            )

    increasing_block = "\n".join(inc_lines)
    decreasing_block = "\n".join(dec_lines)

    tmpl = Template(filename=f"{cfg.path}/templates/monotonic.mako")
    with open(f"{cfg.jobs}/monotonic.py", "w", encoding="utf8") as f:
        f.write(
            tmpl.render(
                increasing_block=increasing_block,
                decreasing_block=decreasing_block,
            )
        )


def _render_scale_script(cfg: PofffConfig) -> None:
    """Render the generated Everest parameter-scaling script.

    Parameters
    ----------
    cfg : PofffConfig
        Shared pofff configuration and derived runtime state."""
    parts = []

    keys = list(cfg.hm.keys())

    for i, p in enumerate(keys):
        lo, hi, scale = cfg.hm[p][1], cfg.hm[p][2], cfg.hm[p][3]

        expr = f"{lo}+coef['{p}']*({hi}-{lo})/(1.0*{scale})"

        comma = "," if i < len(keys) - 1 else ""

        parts.append(f'    para += f"\\"{p}\\":"\n' f'    para += f"{{{expr}}}{comma}"')

    para_block = "\n".join(parts)

    tmpl = Template(filename=f"{cfg.path}/templates/scale.mako")
    with open(f"{cfg.jobs}/scale.py", "w", encoding="utf8") as f:
        f.write(
            tmpl.render(
                para_block=para_block,
            )
        )


def _render_boundary_properties_script(cfg: PofffConfig) -> None:
    """Render the generated boundary-property job script.

    Parameters
    ----------
    cfg : PofffConfig
        Shared pofff configuration and derived runtime state."""
    imports_block = ""

    if cfg.monotonic:
        imports_block += "import sys\n"
        if cfg.everert:
            imports_block += "import os\n"

    if cfg.everert:
        imports_block += "import json"
    else:
        imports_block += "import os"

    monotonic_block = (
        '    if os.path.exists("NOMONOTONIC"):\n' "        sys.exit()\n"
        if cfg.monotonic
        else ""
    )

    if cfg.everert:
        coef_block = (
            '    with open("para.json", "r", encoding="utf8") as f:\n'
            "        coef = json.load(f)\n"
        )
        bcprop_path = '"BCPROP.INC"'
    else:
        coef_block = ""
        bcprop_path = f"os.path.join('{cfg.fol}', \"BCPROP.INC\")"

    if cfg.everert and "pen1" in cfg.hm:
        if cfg.popsize:
            lo, hi, scale = cfg.hm["pen1"][1], cfg.hm["pen1"][2], cfg.hm["pen1"][3]
            val = f"({cfg.pressure}+{lo}+coef['pen1']*({hi}-{lo})/(1.0*{scale}))"
        else:
            val = f"({cfg.pressure}+coef['pen1'])"
    else:
        val = f"({cfg.pressure}+{cfg.para['pen1']})"

    bc_line = f'        file.write(f"1 DIRICHLET WATER 1* {{{val}/1.e5}} /\\n")\n'

    thickness_block = ""

    if cfg.everert and "thicknessmult" in cfg.hm:
        if cfg.popsize:
            lo, hi, scale = (
                cfg.hm["thicknessmult"][1],
                cfg.hm["thicknessmult"][2],
                cfg.hm["thicknessmult"][3],
            )
            mult_val = f"{lo}+coef['thicknessmult']*({hi}-{lo})/(1.0*{scale})"
        else:
            mult_val = "coef['thicknessmult']"

        size = cfg.nxz[0] * cfg.nxz[1]

        lines = ['    with open("THICKNESSMULT.INC", "w", encoding="utf8") as file:']

        for name in ["PV", "X", "X-", "Z", "Z-"]:
            lines.append(f'        file.write("MULT{name}\\n")')
            lines.append(f'        file.write(f"{size}*{{{mult_val}}} /\\n")')

        thickness_block = "\n".join(lines)

    tmpl = Template(filename=f"{cfg.path}/templates/bcprop.mako")
    with open(f"{cfg.jobs}/bcprop.py", "w", encoding="utf8") as f:
        f.write(
            tmpl.render(
                imports_block=imports_block,
                monotonic_block=monotonic_block,
                coef_block=coef_block,
                bcprop_path=bcprop_path,
                bc_line=bc_line,
                thickness_block=thickness_block,
            )
        )


