def _render_flow_script(cfg: PofffConfig) -> None:
    """Render the generated OPM Flow execution script.

    Parameters
    ----------
    cfg : PofffConfig
        Shared pofff configuration and derived runtime state."""
    monotonic_block = (
        'if os.path.exists("NOMONOTONIC"):\n' "    sys.exit()\n"
        if cfg.monotonic
        else ""
    )

    cmd_parts = [f"'{x}'" for x in cfg.flow.split(" ")]
    cmd_str = f"[{', '.join(cmd_parts)}, '{cfg.data}']"

    if cfg.maxtime is not None:
        run_block = f"    p = subprocess.run({cmd_str}, timeout={cfg.maxtime})\n"
    else:
        run_block = f"    p = subprocess.run({cmd_str})\n"

    delete_block = ""
    if cfg.delete:
        delete_block = (
            '    for suff in ["INC", "EGRID", "DBG", "PRT", "SMSPEC", "UNRST", '
            '"UNSMRY", "INIT", "ESMRY", "DATA"]:\n'
            '        os.system(f"rm -rf *.{suff}")\n'
            '    for pref in ["thickness_eval","metr_eval","safu_eval","poro_eval"]:\n'
            '        os.system(f"rm -rf {pref}.*")'
        )

    tmpl = Template(filename=f"{cfg.path}/templates/flow.mako")
    with open(f"{cfg.jobs}/flow.py", "w", encoding="utf8") as f:
        f.write(
            tmpl.render(
                monotonic_block=monotonic_block,
                run_block=run_block,
                delete_block=delete_block,
            )
        )


def _render_region_properties_script(cfg: PofffConfig) -> None:
    """Render the generated regional rock-property script.

    Parameters
    ----------
    cfg : PofffConfig
        Shared pofff configuration and derived runtime state."""
    imports_block = ""

    if cfg.monotonic:
        imports_block += "import sys\n"
        if cfg.everert:
            imports_block += "import os\n"

    if cfg.everert:
        imports_block += "import json"
    else:
        imports_block += "import os"

    monotonic_block = (
        '    if os.path.exists("NOMONOTONIC"):\n' "        sys.exit()\n"
        if cfg.monotonic
        else ""
    )

    if cfg.everert:
        coef_block = (
            '    with open("para.json", "r", encoding="utf8") as f:\n'
            "        coef = json.load(f)\n"
        )
        output_path = '"EQUALREG.INC"'
    else:
        coef_block = ""
        output_path = f"os.path.join('{cfg.fol}', \"EQUALREG.INC\")"

    names = [
        ("poro", "poro"),
        ("permx", "permx"),
        ("permy", "permx"),
        ("permz", "permz"),
        ("disperc", "disperc"),
    ]

    lines = []

    for i in range(1, 8):
        for name, key in names:
            hm_key = f"{name}{i}"
            perm_key = f"perm{i}"
            val = None

            if cfg.everert:
                if hm_key in cfg.hm:
                    if cfg.popsize:
                        lo, hi, scale = (
                            cfg.hm[hm_key][1],
                            cfg.hm[hm_key][2],
                            cfg.hm[hm_key][3],
                        )
                        val = f"{lo}+coef['{hm_key}']*({hi}-{lo})/(1.0*{scale})"
                    else:
                        val = f"coef['{hm_key}']"

                elif name in ("permx", "permy", "permz") and perm_key in cfg.hm:
                    if cfg.popsize:
                        lo, hi, scale = (
                            cfg.hm[perm_key][1],
                            cfg.hm[perm_key][2],
                            cfg.hm[perm_key][3],
                        )
                        val = f"{lo}+coef['{perm_key}']*({hi}-{lo})/(1.0*{scale})"
                    else:
                        val = f"coef['{perm_key}']"

            if val is None:
                val = cfg.para[f"{key}{i}"]

            lines.append(f'        file.write(f"{name.upper()} {{{val}}} {i} F /\\n")')

    body_block = "\n".join(lines)

    tmpl = Template(filename=f"{cfg.path}/templates/equalreg.mako")
    with open(f"{cfg.jobs}/equalreg.py", "w", encoding="utf8") as f:
        f.write(
            tmpl.render(
                imports_block=imports_block,
                monotonic_block=monotonic_block,
                coef_block=coef_block,
                output_path=output_path,
                body_block=body_block,
            )
        )


def _render_saturation_functions_script(cfg: PofffConfig) -> None:
    """Render the generated saturation-function script.

    Parameters
    ----------
    cfg : PofffConfig
        Shared pofff configuration and derived runtime state."""
    imports_block = ""
    if cfg.monotonic:
        imports_block += "import os\nimport sys\n"
    if cfg.everert:
        imports_block += "import json"

    monotonic_block = (
        '    if os.path.exists("NOMONOTONIC"):\n' "        sys.exit()\n"
        if cfg.monotonic
        else ""
    )

    coef_block = (
        '    with open("para.json", "r", encoding="utf8") as f:\n'
        "        coef = json.load(f)\n"
        if cfg.everert
        else ""
    )

    tables_path = '"TABLES.INC"' if cfg.everert else f'"{cfg.fol}/TABLES.INC"'

    names = ["swi", "sni", "pen", "nkrw", "nkrn", "npe", "thre", "npnt"]
    rows = []

    for i in range(1, 8):
        vals = []
        for name in names:
            key = f"{name}{i}"
            val = None

            if cfg.everert and key in cfg.hm:
                if cfg.popsize:
                    lo, hi, scale = (
                        cfg.hm[key][1],
                        cfg.hm[key][2],
                        cfg.hm[key][3],
                    )
                    val = f"{lo}+coef['{key}']*({hi}-{lo})/(1.0*{scale})"
                else:
                    val = f"coef['{key}']"

            if val is None:
                val = cfg.para[key]

            vals.append(val)

        rows.append(f"    safu[{i-1}] = [{', '.join(map(str, vals))}]")

    safu_block = "\n".join(rows)

    tmpl = Template(filename=f"{cfg.path}/templates/satufunc.mako")
    with open(f"{cfg.jobs}/satufunc.py", "w", encoding="utf8") as f:
        f.write(
            tmpl.render(
                imports_block=imports_block,
                krw_expr=cfg.krw.strip(),
                krn_expr=cfg.krn.strip(),
                cap_expr=cfg.cap.strip(),
                monotonic_block=monotonic_block,
                coef_block=coef_block,
                safu_block=safu_block,
                tables_path=tables_path,
            )
        )


def _render_ert_configuration(cfg: PofffConfig) -> None:
    """Render the ERT configuration and forward-model sequence.

    Parameters
    ----------
    cfg : PofffConfig
        Shared pofff configuration and derived runtime state."""
    names = ["copyd", "equalreg", "satufunc", "bcprop", "flow"]
    lines = []
    for name in names:
        lines.append(f"INSTALL_JOB {name} ./jobs/{name.upper()}")
        lines.append(f"FORWARD_MODEL {name}")
    jobs_block = "\n".join(lines)
    random_seed_block = (
        f"RANDOM_SEED {cfg.random_seed}" if cfg.random_seed is not None else ""
    )
    delete_block = ""
    if cfg.delete:
        delete_block = "INSTALL_JOB delete ./jobs/DELETE\nFORWARD_MODEL delete"
    tmpl = Template(filename=f"{cfg.path}/templates/ert.mako")
    rendered = tmpl.render(
        ensembles=cfg.ensembles,
        min_realizations_success=cfg.min_realizations_success,
        cores=cfg.cores,
        random_seed=cfg.random_seed,
        enkf_alpha=cfg.enkf_alpha,
        delete=cfg.delete,
        jobs_block=jobs_block,
        random_seed_block=random_seed_block,
        delete_block=delete_block,
    )
    with open(f"{cfg.fol}/ert.txt", "w", encoding="utf8") as f:
        f.write(rendered)


def _render_everest_configuration(cfg: PofffConfig) -> None:
    """Render the Everest optimization configuration.

    Parameters
    ----------
    cfg : PofffConfig
        Shared pofff configuration and derived runtime state."""
    variables_block = "\n".join(
        [
            f"      - name: {p}\n"
            f"        max: {cfg.hm[p][3]}\n"
            f"        initial_guess: "
            f"{round((cfg.hm[p][0]-cfg.hm[p][1])/((cfg.hm[p][2]-cfg.hm[p][1])/(1.0*cfg.hm[p][3])))}"
            for p in cfg.hm
        ]
    )

    options_names = [
        "strategy",
        "maxiter",
        "popsize",
        "tol",
        "mutation",
        "recombination",
        "rng",
        "callback",
        "disp",
        "polish",
        "init",
        "atol",
        "updating",
        "workers",
        "constraints",
        "x0",
        "integrality",
        "vectorized",
    ]

    options_block = "\n".join(
        [f"    {n}: {getattr(cfg, n)}" for n in options_names if getattr(cfg, n)]
    )

    install_jobs_block = (
        (
            "  - name: scale\n"
            "    executable: jobs/scale.py\n"
            "  - name: monotonic\n"
            "    executable: jobs/monotonic.py\n"
        )
        if cfg.monotonic
        else ""
    ) + "\n".join(
        [
            f"  - name: {n}\n    executable: jobs/{n}.py"
            for n in [
                "copyd",
                "equalreg",
                "satufunc",
                "bcprop",
                "flow",
                "data",
                "metric",
                "delete",
            ]
        ]
    )

    forward_block = (
        ("  - scale\n  - monotonic\n" if cfg.monotonic else "")
        + "\n".join(
            [
                "  - copyd",
                "  - equalreg",
                "  - satufunc",
                "  - bcprop",
                "  - flow",
                (
                    "  - data"
                    f"        -t {cfg.times}\n"
                    f"                -m {cfg.deck}/cellmap.npy"
                ),
                (
                    "  - metric"
                    f"      -t {cfg.times}\n"
                    f"                -e {cfg.experiment}\n"
                    f"                -p {cfg.path}\n"
                    f"                -s {cfg.msat}\n"
                    f"                -c {cfg.mcon}"
                ),
            ]
        )
        + ("\n  - delete" if cfg.delete else "")
    )

